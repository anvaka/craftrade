// Writes public/audio/CREDITS.md from the two manifests (beds.json, hits.json): one line per file with its
// title, author, source page, licence and what was changed. Attribution licences require this to ship.
// Usage: node scripts/audio-credits.mjs [audio folder, default public/audio]
// It also reports what is wrong: a file listed but missing, a file present but not listed, a candidate
// without an author, source or licence, a default that names no candidate. Exit code 1 if any file is missing.
import fs from 'node:fs';
import path from 'node:path';

const dir = path.resolve(process.argv[2] ?? 'public/audio');
const problems = [];
let missing = 0;
const listed = new Set();
const sections = [];

for (const [file, heading] of [['beds.json', 'Ambience beds'], ['hits.json', 'Hits']]) {
  const at = path.join(dir, file);
  if (!fs.existsSync(at)) {
    problems.push(`${file}: not found`);
    continue;
  }
  let m;
  try {
    m = JSON.parse(fs.readFileSync(at, 'utf8'));
  } catch (e) {
    problems.push(`${file}: not valid JSON (${e.message})`);
    continue;
  }
  const lines = [];
  const slots = m.slots && typeof m.slots === 'object' ? m.slots : {};
  for (const slot of Object.keys(slots).sort()) {
    const list = Array.isArray(slots[slot]) ? slots[slot] : [];
    for (const c of list) {
      const id = c?.id ?? '(no id)';
      for (const k of ['title', 'author', 'source', 'licence']) if (!c?.[k]) problems.push(`${file}: ${id} has no ${k}`);
      const files = Array.isArray(c?.files) ? c.files : [];
      if (!files.length) problems.push(`${file}: ${id} lists no files`);
      for (const f of files) {
        listed.add(f);
        if (!fs.existsSync(path.join(dir, f))) {
          problems.push(`${file}: ${id} lists ${f}, which is not there`);
          missing++;
        }
        const licence = c.licenceUrl ? `[${c.licence ?? 'licence'}](${c.licenceUrl})` : (c.licence ?? 'licence not stated');
        const source = c.source ? `[source](${c.source})` : 'source not stated';
        lines.push(`- \`${f}\`: "${c.title ?? id}" by ${c.author ?? 'unknown'}, ${source}, ${licence}. ${c.edits ? `Changes: ${c.edits}` : 'No changes stated.'}`);
      }
    }
    const def = m.default?.[slot];
    if (def && !list.some((c) => c?.id === def)) problems.push(`${file}: the default for ${slot} is ${def}, which is not a candidate`);
  }
  for (const slot of Object.keys(m.default ?? {})) if (!slots[slot]) problems.push(`${file}: a default is given for ${slot}, which has no candidates`);
  sections.push(`## ${heading}\n\n${lines.length ? lines.join('\n') : 'None yet.'}\n`);
}

// files on disk that no manifest mentions
for (const sub of ['beds', 'hits']) {
  const d = path.join(dir, sub);
  if (!fs.existsSync(d)) continue;
  for (const f of fs.readdirSync(d)) if (/\.(mp3|ogg|wav|m4a)$/i.test(f) && !listed.has(`${sub}/${f}`)) problems.push(`${sub}/${f} is in the folder but in no manifest: it has no credit`);
}

const out = `# Audio credits

Recordings used by the game, with their authors and licences. Generated by \`scripts/audio-credits.mjs\` from
\`beds.json\` and \`hits.json\`; do not edit by hand. Every file listed here is a candidate the owner can choose
on the soundboard; all of them ship, so all of them are credited.

${sections.join('\n')}`;
fs.mkdirSync(dir, { recursive: true });
fs.writeFileSync(path.join(dir, 'CREDITS.md'), out);
console.log(`wrote ${path.join(dir, 'CREDITS.md')}: ${listed.size} files credited`);
if (problems.length) console.log(`${problems.length} problem${problems.length === 1 ? '' : 's'}:\n  ${problems.join('\n  ')}`);
process.exit(missing ? 1 : 0);
